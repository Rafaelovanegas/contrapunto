# Prueba de humo en navegador (modo demostración). Uso: python3 tests/e2e.py <url> <carpeta_salida>
import sys
from playwright.sync_api import sync_playwright

url, salida = sys.argv[1], sys.argv[2]
errores = []
with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={'width': 1440, 'height': 900})
    pg.on('console', lambda m: errores.append(m.text) if m.type == 'error' else None)
    pg.on('pageerror', lambda e: errores.append(str(e)))
    pg.goto(url)
    pg.wait_for_selector('text=Audiencia simulada')
    pg.screenshot(path=f'{salida}/1-audiencia.png', full_page=True)
    pg.click('text=El arma la traía en una mochila, ¿verdad?')
    pg.wait_for_selector('.alerta', timeout=8000)
    pg.click('text=La revisión la hizo su compañero Torres, ¿no es así?')
    pg.wait_for_function("document.querySelectorAll('.alerta').length >= 2", timeout=8000)
    pg.screenshot(path=f'{salida}/2-alertas.png', full_page=True)
    n_alertas = pg.locator('.alerta').count()
    pg.click('.pestana:has-text("Semáforo")')
    pg.click('text=1. Usted vio claramente el arma, ¿verdad?')
    pg.wait_for_selector('.semaforo--mal')
    pg.click('text=2. ¿Qué hizo usted al llegar al lugar?')
    pg.wait_for_selector('.semaforo--ok')
    pg.screenshot(path=f'{salida}/3-semaforo.png', full_page=True)
    pg.click('.pestana:has-text("Expediente")')
    pg.wait_for_selector('text=Subir documentos')
    pg.screenshot(path=f'{salida}/4-expediente.png', full_page=True)
    pg.click('.pestana:has-text("Preparación")')
    pg.click('text=Generar propuesta')
    pg.wait_for_selector('.lista-preguntas')
    pg.screenshot(path=f'{salida}/5-preparacion.png', full_page=True)
    pg.click('.pestana:has-text("Ajustes")')
    pg.select_option('select >> nth=1', 'pergamino')
    pg.screenshot(path=f'{salida}/6-ajustes-claro.png', full_page=True)
    m = b.new_page(viewport={'width': 390, 'height': 844})
    m.goto(url)
    m.click('.pestana:has-text("Audiencia")')
    m.wait_for_selector('text=Audiencia simulada')
    m.screenshot(path=f'{salida}/7-movil.png', full_page=True)
    ancho = m.evaluate('document.documentElement.scrollWidth')
    b.close()
print('alertas:', n_alertas, '| ancho movil:', ancho, '| errores:', errores)
